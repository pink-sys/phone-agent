/**
 * 系统提示词。
 *
 * 体量约 4700 字（v1.4.5 瘦身，参考外部瘦身稿 3434 字的框架，但补回了真机
 * 调优换来的关键短句）。曾经写到 13000+ 字、分 14 个编号章节，结果模型在思考里
 * 反复背诵引用它（「根据第 X 节……」），把推理时间花在复读上。对照 DeepSeek
 * Harness 官方提示词（5746 字符、无编号章节、纯祈使句），收回结论：
 * 范式要给，但要写成「已内化的默认动作」，而不是「要逐条执行的手册」。
 *
 * 瘦身的取舍（2026-11-20 评估外部瘦身稿后的定稿）：
 *  - 场景手册移出常驻，靠**精确触发点**送达，不靠模型记得：
 *      微信三步 → phone_input/phone_long_press 工具描述（调用现场必看）
 *        + ScreenOutline 读到 com.tencent.mm 时挂卡 + launch_app 微信成功时挂 note；
 *      小窗 → SMALL_WINDOW_OUTSIDE 报错文案里教放大全屏；
 *      文件块结构 → 各工作台工具自己的 description（本来就有，SYSTEM 里那份是纯重复）；
 *      学习通工序卡 → ScreenOutline 挂卡（v1.4.2 起已有）。
 *  - 没有采纳瘦身稿的「工具描述砍到 55 字」：搜索 query 口径、JSON 转义纪律、
 *    xlsx 数值格这些真金白银的调优都住在描述里，砍了就是倒退。
 *
 * 刻意保持的约束：
 *  - 不用 `$` 符号，避免 Kotlin 模板转义；
 *  - 开头声明「无论以 system 还是 user 送达都有效」——网关降档会把 system
 *    改写成 user，这句话是对那次降级的补偿，让准则不至于随身份一起失效。
 *  - 保留的锚点短语是 tools/test_agent.py 的断言目标，改动时同步改测试。
